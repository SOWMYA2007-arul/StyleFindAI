"""Benchmark foreground masks against KNOWN ground-truth silhouettes (IoU).

Hard synthetic scenes: white-on-white, light garment, dark backdrop, cast shadow, gradient
backdrop, clutter objects, striped garment. Compares the original v1 method, v2 and v2+GrabCut.

    python scripts/benchmark_foreground.py
Writes docs/FOREGROUND_BENCHMARK.md. Real photos need hand-made masks for a true benchmark.
"""
from __future__ import annotations

import random
import time

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

from _common import PROJECT_ROOT
from app.services.foreground import estimate_foreground, legacy_foreground_mask, mask_iou

KINDS = ["white_on_white", "light_garment", "dark_bg", "shadow", "gradient_bg", "clutter", "patterned"]


def scene(kind: str, rng: random.Random):
    w, h = 300, 400
    poly = [(110, 40), (190, 40), (230, 360), (70, 360)]
    gt = Image.new("L", (w, h), 0); ImageDraw.Draw(gt).polygon(poly, fill=255)
    bg, fg = {"white_on_white": ((246, 246, 244), (238, 238, 236)), "light_garment": ((250, 250, 250), (230, 215, 200)),
              "dark_bg": ((25, 25, 30), (180, 40, 60)), "shadow": ((235, 235, 235), (40, 90, 200)),
              "gradient_bg": (None, (200, 120, 40)), "clutter": ((225, 225, 225), (110, 50, 140)),
              "patterned": ((245, 245, 245), (200, 30, 40))}[kind]
    if bg is None:
        img = Image.fromarray((np.linspace(60, 220, h)[:, None, None] * np.ones((h, w, 3))).astype(np.uint8))
    else:
        img = Image.new("RGB", (w, h), bg)
    d = ImageDraw.Draw(img)
    if kind == "shadow":
        d.polygon([(x + 25, y + 15) for x, y in poly], fill=(180, 180, 180))
    d.polygon(poly, fill=fg)
    if kind == "white_on_white":
        d.line(poly + [poly[0]], fill=(215, 215, 212), width=2)
    if kind == "patterned":
        for y in range(40, 360, 18):
            d.line([(0, y), (300, y)], fill=(250, 250, 250), width=5)
        base = Image.new("RGB", (w, h), bg); base.paste(img, (0, 0), gt); img = base
    if kind == "clutter":
        for x, y in [(10, 30), (250, 300), (240, 60)]:
            d.ellipse((x, y, x + 40, y + 40), fill=(rng.randint(0, 255), 0, rng.randint(0, 255)))
    return img.filter(ImageFilter.GaussianBlur(0.8)), np.asarray(gt.resize((192, 256))) > 127


def main() -> None:
    rng = random.Random(1)
    rows = ["# Foreground mask benchmark", "", "IoU against the true garment silhouette (1.0 = perfect). "
            "Generated by `scripts/benchmark_foreground.py`.", "",
            "| scene | v1 (original) | v2 | v2 + GrabCut | v2 method | GrabCut ms |", "|---|---|---|---|---|---|"]
    for k in KINDS:
        img, gt = scene(k, rng)
        _, m1 = legacy_foreground_mask(img)
        f2 = estimate_foreground(img)
        t = time.perf_counter(); f3 = estimate_foreground(img, refine=True); ms = (time.perf_counter() - t) * 1000
        rows.append(f"| {k} | {mask_iou(m1, gt):.2f} | {mask_iou(f2.mask, gt):.2f} | {mask_iou(f3.mask, gt):.2f} | "
                    f"{f2.method} | {ms:.0f} |")
        print(rows[-1])
    (PROJECT_ROOT / "docs" / "FOREGROUND_BENCHMARK.md").write_text("\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
